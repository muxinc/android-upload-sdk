package com.mux.video.upload.internal.standardization

import com.mux.video.upload.api.HdrHandling
import com.mux.video.upload.internal.InputStandardization

/** Proof for this source and conversion path, supplied by the caller, never inferred from a codec list. */
internal data class PlanningCapabilities(
  val sourceIsDecodable: Boolean = false,
  val encodableVideoCodecs: Set<VideoCodec> = emptySet(),
  /** A FrameRate entry must prove cadence conversion while preserving the effective source timeline. */
  val remediableRequirements: Set<PolicyRequirement> = emptySet(),
  val toneMappableDynamicRanges: Set<DynamicRange> = emptySet(),
  /** Proven first-track AAC preparation, including decode/encode or compliant AAC copy and muxing. */
  val canProduceAacAudio: Boolean = false,
  // These ranges allow unchanged bytes after media eligibility checks. They are not conversion capabilities.
  // Unlike conversion, pass-through does not need a local encoder or a server-configuration probe.
  val preservableHdrDynamicRanges: Set<DynamicRange> = setOf(DynamicRange.Hlg, DynamicRange.Pq),
) {
  fun missingCapabilities(conversion: StandardInputConversion): Set<ConversionCapabilityFailure> = buildSet {
    if (!sourceIsDecodable) add(ConversionCapabilityFailure.SourceDecode)
    if (conversion.outputCodec !in encodableVideoCodecs) add(ConversionCapabilityFailure.VideoEncode)
    for (requirement in conversion.requirementsToRemediate - remediableRequirements) {
      add(ConversionCapabilityFailure.Remediation(requirement))
    }
    if (conversion.outputAudio != OutputAudio.None && !canProduceAacAudio) {
      add(ConversionCapabilityFailure.AacAudioPreparation)
    }
    if (conversion.toneMapsToSdr && conversion.sourceDynamicRange !in toneMappableDynamicRanges) {
      add(ConversionCapabilityFailure.ToneMapping)
    }
  }
}

/** Missing proof for the codec, range, and requirements carried by the associated conversion. */
internal sealed interface ConversionCapabilityFailure {
  data object SourceDecode : ConversionCapabilityFailure
  data object VideoEncode : ConversionCapabilityFailure
  data class Remediation(val requirement: PolicyRequirement) : ConversionCapabilityFailure
  data object AacAudioPreparation : ConversionCapabilityFailure
  data object ToneMapping : ConversionCapabilityFailure
}

internal enum class OutputAudio {
  None,
  /** Produce AAC from audio track ordinal zero. Compliant AAC may be copied; this adds no surround encoder. */
  AacFromFirstTrack,
  /** Unknown audio presence must be resolved during preparation, never interpreted as silence. */
  AacFromFirstTrackIfPresent,
}

/** Whole-file SDR conversion with concrete output targets. Generated bytes require reinspection before upload. */
internal data class StandardInputConversion(
  val sourceCodec: VideoCodec,
  val outputCodec: VideoCodec,
  val sourceDynamicRange: DynamicRange,
  val sourceDisplayDimensions: Dimensions,
  /** Explicit HDR-to-BT.709 SDR pixel conversion; retagging metadata is insufficient. */
  val toneMapsToSdr: Boolean,
  val selection: PolicySelection,
  /** Other policy violations requiring proof; explicit AAC preparation and tone mapping supply their own. */
  val requirementsToRemediate: Set<PolicyRequirement>,
  val outputDimensions: Dimensions,
  val outputFrameRate: Double,
  val outputPixelFormat: PixelFormat,
  val outputAudio: OutputAudio,
) {
  val outputDynamicRange: DynamicRange get() = DynamicRange.Sdr
}

internal sealed interface OriginalReason {
  data object StandardizationNotRequested : OriginalReason
  data object StandardInput : OriginalReason
  data object NoKnownStandardInputViolation : OriginalReason
  data class PreserveHdr(val dynamicRange: DynamicRange) : OriginalReason
}

internal sealed interface FallbackReason {
  data object InsufficientEvidence : FallbackReason
  data object UnsafeVideoTrackStructure : FallbackReason
  data class UnsupportedConversion(
    val conversion: StandardInputConversion,
    val missingCapabilities: Set<ConversionCapabilityFailure>,
  ) : FallbackReason
  data class UnsupportedHdr(val dynamicRange: DynamicRange) : FallbackReason
  data class HdrPreservationUnavailable(val dynamicRange: DynamicRange) : FallbackReason
  data class NonStandardHdr(
    val dynamicRange: DynamicRange,
    val requirements: Set<PolicyRequirement>,
  ) : FallbackReason
}

internal sealed interface StandardInputAction {
  data class UploadOriginal(val reason: OriginalReason) : StandardInputAction
  data class Convert(val conversion: StandardInputConversion) : StandardInputAction
  /** A categorized local failure still selects original bytes; cancellation belongs to orchestration. */
  data class Fallback(val reason: FallbackReason) : StandardInputAction
}

/** Evaluation describes published source compliance; the action also enforces the selected output size. */
internal data class StandardInputPlan(val action: StandardInputAction, val evaluation: PolicyEvaluation)

internal class StandardInputPlanner(
  private val evaluator: StandardInputPolicyEvaluator = StandardInputPolicyEvaluator(),
) {
  fun plan(
    facts: MediaFacts,
    options: InputStandardization = InputStandardization(),
    capabilities: PlanningCapabilities = PlanningCapabilities(),
  ): StandardInputPlan {
    val selection = PolicySelection(options.maximumResolution)
    // Retain source diagnostics even when preparation is disabled; this does no inspection or device probing.
    val evaluation = evaluator.evaluate(facts, selection)
    fun original(reason: OriginalReason) = StandardInputPlan(StandardInputAction.UploadOriginal(reason), evaluation)
    fun fallback(reason: FallbackReason) = StandardInputPlan(StandardInputAction.Fallback(reason), evaluation)

    if (!options.standardizationRequested) return original(OriginalReason.StandardizationNotRequested)
    val trackCount = facts.videoTrackCount.valueOrNull
    if (trackCount != null && trackCount != 1) return fallback(FallbackReason.UnsafeVideoTrackStructure)

    val requirements = evaluation.nonCompliantRequirements.toMutableSet()
    facts.displayDimensions.valueOrNull?.takeIf { it.isValid }?.let {
      if (!it.fitsWithin(selection.generatedOutputDimensions)) requirements.add(PolicyRequirement.VideoResolution)
    }
    val range = facts.dynamicRange.valueOrNull
    val toneMap = (range == DynamicRange.Hlg || range == DynamicRange.Pq) &&
      options.hdrHandling == HdrHandling.ToneMapToSDR
    when (range) {
      DynamicRange.DolbyVision, DynamicRange.OtherHdr -> return fallback(FallbackReason.UnsupportedHdr(range))
      DynamicRange.Hlg, DynamicRange.Pq -> {
        val codec = facts.videoCodec.valueOrNull ?: return fallback(FallbackReason.InsufficientEvidence)
        if (codec == VideoCodec.Other) return fallback(FallbackReason.UnsupportedHdr(range))
        if (!toneMap) {
          if (codec != VideoCodec.Hevc) return fallback(FallbackReason.UnsupportedHdr(range))
          when (evaluation.checks.getValue(PolicyRequirement.DynamicRange)) {
            PolicyStatus.Unknown -> return fallback(FallbackReason.InsufficientEvidence)
            PolicyStatus.NonCompliant -> return fallback(FallbackReason.UnsupportedHdr(range))
            PolicyStatus.Compliant -> Unit
          }
          if (range !in capabilities.preservableHdrDynamicRanges) {
            return fallback(FallbackReason.HdrPreservationUnavailable(range))
          }
          if (requirements.isNotEmpty()) return fallback(FallbackReason.NonStandardHdr(range, requirements.toSet()))
          return original(OriginalReason.PreserveHdr(range))
        }
      }
      null -> if (requirements.isNotEmpty()) return fallback(FallbackReason.InsufficientEvidence)
      DynamicRange.Sdr -> Unit
    }
    if (requirements.isEmpty() && !toneMap) return original(
      if (evaluation.outcome == PolicyStatus.Compliant) OriginalReason.StandardInput
      else OriginalReason.NoKnownStandardInputViolation)

    val conversion = buildConversion(facts, selection, requirements.toSet(), toneMap)
      ?: return fallback(FallbackReason.InsufficientEvidence)
    val missingCapabilities = capabilities.missingCapabilities(conversion)
    return if (missingCapabilities.isEmpty()) StandardInputPlan(StandardInputAction.Convert(conversion), evaluation)
    else fallback(FallbackReason.UnsupportedConversion(conversion, missingCapabilities))
  }

  private fun buildConversion(
    facts: MediaFacts,
    selection: PolicySelection,
    requirements: Set<PolicyRequirement>,
    toneMap: Boolean,
  ): StandardInputConversion? {
    val codec = facts.videoCodec.valueOrNull ?: return null
    val range = facts.dynamicRange.valueOrNull ?: return null
    val sourceSize = facts.displayDimensions.valueOrNull ?: return null
    val outputSize = sourceSize.scaledToFit(selection.generatedOutputDimensions) ?: return null
    val sourceFrameRate = facts.frameRate.valueOrNull?.takeIf { it.isFinite() && it > 0 } ?: return null
    val outputCodec = if (codec == VideoCodec.Other) VideoCodec.H264 else codec
    val outputLimits = evaluator.applicableLimits(MediaFact.Known(outputSize), selection).single()
    val frameRate = if (sourceFrameRate in outputLimits.frameRateRange) sourceFrameRate else 30.0
    val audio = facts.audioTracks.valueOrNull
    val keepTenBit = !toneMap && outputCodec == VideoCodec.Hevc &&
      facts.pixelFormat.valueOrNull == PixelFormat(10, ChromaSubsampling.Yuv420)
    return StandardInputConversion(
      sourceCodec = codec,
      outputCodec = outputCodec,
      sourceDynamicRange = range,
      sourceDisplayDimensions = sourceSize,
      toneMapsToSdr = toneMap,
      selection = selection,
      // These operations have dedicated proof, regardless of how much source inspection established.
      requirementsToRemediate = requirements - PolicyRequirement.Audio -
        (if (toneMap) setOf(PolicyRequirement.DynamicRange) else emptySet()),
      outputDimensions = outputSize,
      outputFrameRate = frameRate,
      outputPixelFormat = PixelFormat(if (keepTenBit) 10 else 8, ChromaSubsampling.Yuv420),
      outputAudio = when {
        audio == null -> OutputAudio.AacFromFirstTrackIfPresent
        audio.isEmpty() -> OutputAudio.None
        else -> OutputAudio.AacFromFirstTrack
      },
    )
  }
}
